/// PRD §5-1.1 "기기 연동 모드에 따른 홈 탭 UI 자동 전환".
///
/// 세트가 가진 기기 조합에서 도출되는 분류. 구 서브탭 분기(HomeSubTab·
/// defaultTab·controlEnabled 등)는 2026-09-02 홈 단일 스크롤 개편으로
/// 폐기됐다(2026-09-04 정리) — 분류 자체는 후속 화면 분기의 근거로 남긴다.
enum DeviceMode {
  /// 통합 세트 — 캠 + 제어기 둘 다.
  integrated,

  /// 사육장 단품 — 제어기만. 상단은 개체 프로필 카드로 대체.
  cageOnly,

  /// 캠 단품 — 캠만. 사육장 제어 서브탭 비활성.
  camOnly,

  /// 기기 미연동 — 사육장만 등록된 상태. PRD 미명세이나 등록 직후 실재한다.
  none;
}
